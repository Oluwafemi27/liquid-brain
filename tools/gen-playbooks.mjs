// Regenerates src/playbooks/library.gen.ts from src/playbooks/content/*.md so the playbooks ship inside the
// server bundle as plain strings (no filesystem reads at runtime, works on Vercel). Run: node tools/gen-playbooks.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../src/playbooks/content/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "LICENSES.md").sort();
const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.md$/, ""))}: ${JSON.stringify(readFileSync(new URL(f, dir), "utf8"))},`);
writeFileSync(
  new URL("../src/playbooks/library.gen.ts", import.meta.url),
  `// GENERATED by tools/gen-playbooks.mjs from content/*.md. Do not edit. Licences: content/LICENSES.md (MIT).\nexport const PLAYBOOK_SOURCES: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`wrote ${files.length} playbooks`);
